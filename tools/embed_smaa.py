#!/usr/bin/env python3
"""Rebuild embedded shader/area data from the bundled permissively licensed SMAA sources."""
from pathlib import Path
import struct
root = Path(__file__).resolve().parents[1]
source = (root / 'third_party/smaa/SMAA.hlsl').read_text(encoding='utf-8')
# MSVC C2026: individual string tokens must fit below 16380 bytes. Keep
# chunks separate array elements, then join once; never create one giant token.
chunks = []
current = ''
for char in source:
    if len((current + char).encode('utf-8')) > 8192:
        chunks.append(current)
        current = ''
    current += char
if current:
    chunks.append(current)
assert all(')SMAA"' not in chunk for chunk in chunks)
header = ('#pragma once\n#include <string>\n'
          '// Generated by tools/embed_smaa.py. Preserve the complete SMAA source.\n'
          'static const std::string smaaReference = [] {\n'
          '    static const char *const chunks[] = {\n')
header += ''.join('R"SMAA(' + chunk + ')SMAA",\n' for chunk in chunks)
header += ('    };\n    std::string result;\n'
           f'    result.reserve({len(source.encode("utf-8"))});\n'
           '    for (const char *chunk : chunks) result.append(chunk);\n'
           '    return result;\n}();\n')
(root / 'src/smaa_shader.hpp').write_text(header, encoding='utf-8', newline='\n')
dds = (root / 'third_party/smaa/Textures/AreaTexDX10.dds').read_bytes()
assert dds[:4] == b'DDS '
height, width = struct.unpack_from('<II', dds, 12)
bits = struct.unpack_from('<I', dds, 88)[0]
assert (width, height, bits) == (160, 560, 24)
assert struct.unpack_from('<III', dds, 92) == (0xff0000, 0xff00, 0xff)
# DDS is BGR24; SMAA GLSL reads the original red/green area channels.
area = bytes(c for i in range(width * height) for c in (dds[128+i*3+2], dds[128+i*3+1]))
(root / 'src/smaa_area.hpp').write_text('#pragma once\nstatic const unsigned char smaaAreaBytes[]={\n' + ','.join(map(str, area)) + '\n};\n')
